const source=fs.readFileSync(filename,'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod=new Module(filename);mod.filename=filename;mod.paths=Module._nodeModulePaths(path.dirname(filename));mod._compile(compiled,filename);
const api=mod.exports;
const basic='Basic '+Buffer.from('YWONDER_SHOP_TEST:qa-only-secret').toString('base64');
assert.equal(api.validVietQrBasic(basic),true);
assert.equal(api.validVietQrBasic('Basic '+Buffer.from('YWONDER_SHOP_TEST:wrong').toString('base64')),false);
assert.equal(api.validVietQrBasic(null),false);
const issued=api.issueVietQrToken();
assert.equal(issued.token_type,'Bearer');assert.equal(issued.expires_in,300);
assert.equal(api.validVietQrBearer('Bearer '+issued.access_token),true);
assert.equal(api.validVietQrBearer('Bearer '+issued.access_token.slice(0,-1)+'x'),false);
assert.equal(api.validVietQrBearer(null),false);
assert.equal(api.vietQrAutoVerifyEnabled(),false);
