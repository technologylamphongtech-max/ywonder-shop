const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const {PrismaClient}=require('@prisma/client');
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText,file);
const {captureAffiliateOrder,accrueAffiliateOrder,PHONG_CHAU_STORE_ID}=require('../src/lib/affiliate.ts');
const {closePhongChauPool,phongChauPoolReport,confirmPhongChauPoolPayment,setPhongChauWithdrawalWindow,requestPhongChauWithdrawal}=require('../src/lib/affiliate-pool.ts');
const database=path.resolve(process.argv[2]).replaceAll('\\','/');
const db=new PrismaClient({datasources:{db:{url:'file:'+database}}});
const sql=tx=>({$executeRawUnsafe:tx.$executeRawUnsafe.bind(tx),$queryRawUnsafe:async(...args)=>JSON.parse(JSON.stringify(await tx.$queryRawUnsafe(...args),(_,v)=>typeof v==='bigint'?Number(v):v))});
(async()=>{
 const read=sql(db);
 const order=(await read.$queryRawUnsafe("SELECT * FROM MarketOrder WHERE id='link-order'"))[0];
 const items=await read.$queryRawUnsafe("SELECT * FROM MarketOrderItem WHERE orderId='link-order'");
 await db.$transaction(tx=>captureAffiliateOrder(sql(tx),order.id,'buyer','a'));
 await db.$transaction(tx=>accrueAffiliateOrder(sql(tx),order,items));
 await db.$transaction(tx=>accrueAffiliateOrder(sql(tx),order,items));
 const commissions=await read.$queryRawUnsafe("SELECT beneficiaryId,kind,level,rateBps,revenue,amount,sourceKey FROM MarketAffiliateCommission WHERE orderId='link-order'");
 assert.deepEqual(commissions,[{beneficiaryId:'a',kind:'CONNECTION',level:1,rateBps:2000,revenue:2500000,amount:500000,sourceKey:PHONG_CHAU_STORE_ID}]);
 await db.$executeRawUnsafe("INSERT INTO MarketOrder VALUES('legacy-order','buyer',2500000,0,'COMPLETED')");
 await db.$executeRawUnsafe('INSERT INTO MarketOrderItem VALUES(?,?,?,?)','legacy-item','legacy-order',PHONG_CHAU_STORE_ID,2500000);
 await db.$executeRawUnsafe("INSERT INTO MarketAffiliateOrder VALUES('legacy-order',1)");
 await db.$executeRawUnsafe("INSERT INTO MarketAffiliateOrderChain VALUES('legacy-order',1,'a')");
 const legacyOrder=(await read.$queryRawUnsafe("SELECT * FROM MarketOrder WHERE id='legacy-order'"))[0];
 const legacyItems=await read.$queryRawUnsafe("SELECT * FROM MarketOrderItem WHERE orderId='legacy-order'");
 await db.$transaction(tx=>accrueAffiliateOrder(sql(tx),legacyOrder,legacyItems));
 const oldRate=(await read.$queryRawUnsafe("SELECT rateBps,amount FROM MarketAffiliateCommission WHERE orderId='legacy-order'"))[0];
 assert.deepEqual(oldRate,{rateBps:100,amount:25000});
 await assert.rejects(()=>db.$transaction(tx=>closePhongChauPool(sql(tx),'2099-01','admin')),/Chỉ chốt tháng/);
 const close=await db.$transaction(tx=>closePhongChauPool(sql(tx),'2025-09','admin'));
 assert.equal(close.revenue,113500000);assert.equal(close.groupCount,3);assert.equal(close.poolAmount,34050000);assert.equal(close.eligibleCount,30);
 const repeat=await db.$transaction(tx=>closePhongChauPool(sql(tx),'2025-09','admin'));
 assert.equal(repeat.alreadyClosed,true);
 const report=await phongChauPoolReport(read);
 assert.match(report.period,/^\d{4}-(0[1-9]|1[0-2])$/);
 const shares=report.shares.filter(row=>row.period==='2025-09');
 assert.equal(shares.length,30);assert(shares.every(row=>row.qualifiedF1===10));
 assert.equal(shares.reduce((sum,row)=>sum+row.amount,0),34050000);
 for(const group of report.groups){const part=shares.filter(row=>row.groupId===group.id);assert.equal(part.length,10);assert.equal(part.reduce((sum,row)=>sum+row.amount,0),11350000);assert.equal(part.reduce((sum,row)=>sum+row.shareBps,0),10000);}
 assert.equal(shares.filter(row=>row.referrerId==='a').length,20);
 assert.equal(shares.filter(row=>row.referrerId==='b').length,10);
 assert(!shares.some(row=>['a','b','c','a20','a21','a22','a23','a24'].includes(row.beneficiaryId)));
 const a0=shares.find(row=>row.beneficiaryId==='a0'),a1=shares.find(row=>row.beneficiaryId==='a1');
 assert.equal(a0.orderCount,2);assert.equal(a0.orderRevenue,3500000);assert(a0.amount>a1.amount);
 assert.equal(report.groups.length,3);assert(report.groups.every(row=>row.poolAmount===11350000));
 const first=shares[0];
 const withdraw={shareId:first.id,bankName:'NAB',bankAccount:'123456789',accountName:'F1 TEST'};
 await assert.rejects(()=>db.$transaction(tx=>requestPhongChauWithdrawal(sql(tx),first.beneficiaryId,withdraw)),/chưa mở rút/);
 await assert.rejects(()=>db.$transaction(tx=>setPhongChauWithdrawalWindow(sql(tx),'admin','2025-10',true)),/Phải chốt quỹ/);
 await db.$transaction(tx=>setPhongChauWithdrawalWindow(sql(tx),'admin','2025-09',true));
 const buyerReport=await phongChauPoolReport(read,first.beneficiaryId);
 assert.equal(buyerReport.wallet.available,first.amount);
 assert.equal(buyerReport.shares.find(row=>row.id===first.id).withdrawalOpen,1);
 await assert.rejects(()=>db.$transaction(tx=>requestPhongChauWithdrawal(sql(tx),'a',withdraw)),/không tồn tại/);
 const requested=await db.$transaction(tx=>requestPhongChauWithdrawal(sql(tx),first.beneficiaryId,withdraw));
 assert.equal(requested.amount,first.amount);
 await assert.rejects(()=>db.$transaction(tx=>requestPhongChauWithdrawal(sql(tx),first.beneficiaryId,withdraw)),/đã được yêu cầu rút/);
 await db.$transaction(tx=>setPhongChauWithdrawalWindow(sql(tx),'admin','2025-09',false));
 assert.equal((await phongChauPoolReport(read,first.beneficiaryId)).wallet.requested,first.amount);
 const payment={ids:[first.id],expectedAmount:first.amount,reference:'BANK-TEST-1',requestId:'pool-qa-1',note:'test',confirmed:true};
 const paid=await db.$transaction(tx=>confirmPhongChauPoolPayment(sql(tx),'admin',payment));assert.equal(paid.alreadyConfirmed,false);
 const replay=await db.$transaction(tx=>confirmPhongChauPoolPayment(sql(tx),'admin',payment));assert.equal(replay.alreadyConfirmed,true);
 assert.equal((await read.$queryRawUnsafe('SELECT status FROM MarketAffiliatePoolShare WHERE id=?',first.id))[0].status,'PAID');
 assert.equal((await read.$queryRawUnsafe('SELECT status FROM MarketAffiliatePoolWithdrawal WHERE shareId=?',first.id))[0].status,'PAID');
 console.log('PASS Phong Chau: F1 20%, 3 weighted pools, wallet locked by default, admin opens rút, buyer ownership, single request, payout confirmation and replay');
})().catch(error=>{console.error(error);process.exitCode=1}).finally(()=>db.$disconnect());
